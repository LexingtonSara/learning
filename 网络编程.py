# 1.2 网络核心词汇
"""
1.IP地址: 网络设备的唯一标识符,由32位二进制数表示,通常用点分十进制表示,如192.168.1.1.分为网络地址+主机地址
子网掩码: 用于标识IP地址的子网范围,用于区分同一子网内的不同主机,如255.255.255.0.二进制1的个数表示子网掩码的位数.
网络地址相同的所有IP属于同一个网段,局域网内的主机可以直接通信.
2.DHCP: 动态主机配置协议,用于自动分配IP地址,防止IP地址冲突.
电脑分配IP有两种方式,手动设置和自动获取.
3.内网和公网IP: 内网IP是局域网内的IP地址,公网IP是Internet上唯一的IP地址.
4.云服务器: 不用自己搭建服务器,由云服务商提供,可以按需付费.
5.端口: 取值范围1~65535,很多端口已经被系统占用,尽量使用5000之后的端口.每个程序通过网络进行通讯都必须指定一个端口
6.域名: 域名是IP地址的别名,域名系统(DNS)负责将域名转换为IP地址.
寻找IP地址的方法:在自己电脑的DNS缓存中查看,
如果未找到去自己电脑的hosts文件中查找,
如果还未找到,在自己电脑上找到DNS配置的地址(本地域名服务器)去寻找域名对应的IP,
如果还未找到,去根域名服务器(全球共13台,距离中国最近的服务器在日本)查找.
根域名服务器/顶级域名服务器.org .com .cn /二级域名服务器www.

"""

