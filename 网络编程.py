# UDP协议:无连接,不保证数据顺序,不保证可靠性,适合实时性要求高的场景,如视频会议,直播等.
# TCP协议:面向连接,保证数据顺序,可靠性,适合可靠性要求高的场景,如文件传输,电子邮件等.
# TCP协议的三次握手建立连接,四次挥手断开连接.
"""
客户端向服务端发送一个syn包,服务端收到syn包后,会发送一个syn+ack包,客户端收到syn+ack包后,会发送一个ack包,三次握手完成.
发送请求,服务端收到请求,处理请求,返回响应,客户端收到响应,发送ack包进行确认,三次握手完成.
ack包:确认序号,确认对方收到的数据.应答
syn包:同步序号,建立连接.
fin包:结束连接.
客户端向服务端发送一个fin包,服务端收到fin包后,会先返回一个ack包,然后再处理请求,处理完成后,再返回一个fin包,客户端收到fin包后,
会返回一个ack包,四次挥手完成.
"""

# 5.粘包与拆包
"""
两台电脑在进行数据传输时,不是直接将数据传输给对方
对于发送者,执行sendall/send 发送消息时,先将数据发送至缓冲区,然后再将缓冲区中的数据发送给对方
对于接收者,执行recv/recvfrom 接收消息时,先接收对方发送的消息,然后再将接收到的消息放入缓冲区,最后再返回缓冲区中的数据给调用者
如果一次请求发送的数据量较小,没达到缓冲区的大小,TCP会将多个请求合并为同一个请求进行发送,这就是粘包
如果一次请求发送的数据量较大,超过了缓冲区的大小,TCP会将多个请求拆分为多个请求进行发送,这就是拆包
"""